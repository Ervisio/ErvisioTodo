export function matchOperation(path: string, method: string) {
  const matches = API_OPERATIONS.filter((operation) =>
    new RegExp("^" + operation.path.replace(/\{[^}]+\}/g, "[^/]+") + "$").test(
      path,
    ),
  );
  return {
    operation: matches.find((operation) => operation.method === method),
    allowed: matches.map((operation) => operation.method),
  };
}
